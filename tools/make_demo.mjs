// Generates the synthetic demo dataset published with the site (demo/).
// Deterministic: same output on every run. Usage: node tools/make_demo.mjs
import fs from 'fs';
import path from 'path';

// mulberry32: small, well-distributed PRNG.
let seed = 42;
const rand = () => {
  seed = (seed + 0x6D2B79F5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};
const gauss = () => Math.sqrt(-2 * Math.log(rand() + 1e-12)) * Math.cos(2 * Math.PI * rand());
const noisy = (v, cv) => Math.max(0, v * (1 + cv * gauss()));

// Column header names as they appear in the instrument exports.
const COMPOUNDS = [
  ['Benzyldimethyldodecylammonium', 'C12BDMA', 2.1e8, 0.42],
  ['Benzyldimethyltetradecylammonium', 'C14BDMA', 1.3e8, 0.61],
  ['Dodecyltrimethylammonium', 'C12TMA', 8.8e7, 0.37],
  ['Tetradecyltrimethylammonium', 'C14TMA', 7.0e7, 0.37],
  ['BDMA', 'BDMA', 2.6e7, 0.23],
];
const IS = ['d3MTP', 1.0e7];
const header = ['Sample Name', ...COMPOUNDS.flatMap(([n]) => [`${n}-1`, `${n}-2`]), `${IS[0]}-1`, `${IS[0]}-2`];

function row(name, conc, isScale = 1) {
  const is = noisy(IS[1] * isScale, 0.05);
  const cells = [name];
  for (const [, id, resp, ratio] of COMPOUNDS) {
    const c = conc[id] || 0;
    const a = c > 0 ? noisy(resp * c * (is / IS[1]) * (1 - 0.6 * c), 0.04) + 2000 * rand() : 1500 + 2500 * rand();
    cells.push(a.toFixed(4), noisy(a * ratio, 0.05).toFixed(4));
  }
  cells.push(is.toFixed(4), (is * 0.3).toFixed(4));
  return cells.join('\t');
}

const out = path.resolve('demo');
fs.mkdirSync(out, { recursive: true });

// Calibration: 6 levels in duplicate, all analytes at the same level.
const levels = [0.005, 0.01, 0.025, 0.05, 0.1, 0.25];
const calRows = [];
for (let rep = 0; rep < 2; rep++) for (const l of levels) calRows.push(row(`${l}_uM_QACs`, Object.fromEntries(COMPOUNDS.map(([, id]) => [id, l]))));
fs.writeFileSync(path.join(out, 'demo_calibration.txt'), [header.join('\t'), ...calRows].join('\n') + '\n');

// Kinetics: three substrates, 0–240 min, triplicates, 100× dilution, C0 ≈ 20 µM.
const k = { C12BDMA: 2.4, C12TMA: 0.9, C14TMA: 1.3 };   // h⁻¹
const code = { C12BDMA: 'B12', C12TMA: 'T12', C14TMA: 'T14' };
const kin = [row('acn1', {})];
for (const sub of Object.keys(k)) for (let rep = 1; rep <= 3; rep++) {
  for (const m of [0, 20, 40, 60, 90, 120, 180, 240]) {
    const c = 20 * Math.exp(-k[sub] * m / 60) / 100;
    const conc = { [sub]: c };
    if (sub === 'C12BDMA') conc.BDMA = 20 * (1 - Math.exp(-k[sub] * m / 60)) * 0.9 / 100;
    kin.push(row(`${code[sub]}_${m}m_${rep}`, conc, 1 + 0.08 * gauss()));
  }
  kin.push(row('acn2', {}));
}
fs.writeFileSync(path.join(out, 'demo_kinetics.txt'), [header.join('\t'), ...kin].join('\n') + '\n');

// End-point: two enzymes × four substrates, 0 and 24 h, triplicates.
const remaining = { EnzA: { C12BDMA: 0.02, C14BDMA: 0.05, C12TMA: 0.10, C14TMA: 0.04 }, EnzB: { C12BDMA: 0.85, C14BDMA: 0.95, C12TMA: 0.60, C14TMA: 0.75 } };
const gcode = { C12BDMA: 'c12', C14BDMA: 'c14', C12TMA: 'c12t', C14TMA: 'c14t' };
const ep = [row('acn', {})];
for (const enz of Object.keys(remaining)) for (const sub of Object.keys(gcode)) for (const t of [0, 24]) for (let rep = 1; rep <= 3; rep++) {
  const frac = t === 0 ? 1 : remaining[enz][sub];
  const conc = { [sub]: noisy(2.2 * frac, 0.05) / 100 };
  if (sub.endsWith('BDMA') && t === 24) conc.BDMA = 2.2 * (1 - frac) * 0.8 / 100;
  ep.push(row(`${enz.toLowerCase()}_${gcode[sub]}_t${t}_r${rep}`, conc, 1 + 0.06 * gauss()));
}
fs.writeFileSync(path.join(out, 'demo_endpoint.txt'), [header.join('\t'), ...ep].join('\n') + '\n');

const registry = {
  _readme: 'Synthetic demo data generated by tools/make_demo.mjs. Not real measurements.',
  calibrations: [{ id: 'demo_cal', label: 'Demo calibration · d3-MTP IS', file: 'demo_calibration.txt', is: 'd3MTP', isConc: 0.022 }],
  experiments: [
    { id: 'demo_endpoint', title: 'Demo · two enzymes · 0 vs 24 h', file: 'demo_endpoint.txt', design: 'endpoint', calibrations: ['demo_cal'], dilution: 100, c0: 2.2,
      conditions: { enza: 'Enzyme A', enzb: 'Enzyme B' }, groupOrder: ['C12TMA', 'C14TMA', 'C12BDMA', 'C14BDMA'] },
    { id: 'demo_kinetics', title: 'Demo · chain-length kinetics · 0–240 min', file: 'demo_kinetics.txt', design: 'timecourse', displayTimeUnit: 'min', calibrations: ['demo_cal'], dilution: 100, c0: 20,
      groupOrder: ['C12TMA', 'C14TMA', 'C12BDMA'] },
  ],
};
fs.writeFileSync(path.join(out, 'experiments.json'), JSON.stringify(registry, null, 2) + '\n');
console.log('demo/ written');
